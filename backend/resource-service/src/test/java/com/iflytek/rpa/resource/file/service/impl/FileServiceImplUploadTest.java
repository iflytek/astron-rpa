class FileServiceImplUploadTest {

    private final Map<String, byte[]> objects = new HashMap<>();
    private FileService service;
    private FileServiceImpl target;
    private FileMapper mapper;
    private FileMapper realMapper;
    private JdbcTemplate jdbc;
    private JdbcTransactionManager transactionManager;
    private FaultInjectingDataSource dataSource;
    private S3Client s3;
    private MockedStatic<S3Client> clientFactory;

    @BeforeEach
    void setUp() throws Exception {
        JdbcDataSource database = new JdbcDataSource();
        database.setURL("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
        dataSource = new FaultInjectingDataSource(database);
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("CREATE TABLE file (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "file_id VARCHAR(50), path VARCHAR(100), file_name VARCHAR(1000), "
                + "create_time TIMESTAMP, update_time TIMESTAMP, deleted INT DEFAULT 0)");
        transactionManager = new JdbcTransactionManager(dataSource);

        MybatisConfiguration configuration = new MybatisConfiguration();
        configuration.addMapper(FileMapper.class);
        MybatisSqlSessionFactoryBean sessionFactory = new MybatisSqlSessionFactoryBean();
        sessionFactory.setDataSource(dataSource);
        sessionFactory.setConfiguration(configuration);
        realMapper = new SqlSessionTemplate(sessionFactory.getObject()).getMapper(FileMapper.class);
        mapper = spy(realMapper);

        S3Config config = new S3Config();
        config.setUrl("http://localhost:9999");
        config.setBucket("test-bucket");
        config.setAccessKey("test-access");
        config.setSecretKey("test-secret");
        IdWorker idWorker = mock(IdWorker.class);
        when(idWorker.nextId()).thenReturn(123L);
        target = new FileServiceImpl();
        ReflectionTestUtils.setField(target, "baseMapper", mapper);
        ReflectionTestUtils.setField(target, "s3Config", config);
        ReflectionTestUtils.setField(target, "idWorker", idWorker);
        ProxyFactory proxyFactory = new ProxyFactory(target);
        proxyFactory.addAdvice(
                new TransactionInterceptor(transactionManager, new AnnotationTransactionAttributeSource()));
        service = (FileService) proxyFactory.getProxy();

        s3 = mock(S3Client.class);
        when(s3.putObject(any(PutObjectRequest.class), any(RequestBody.class))).thenAnswer(invocation -> {
            PutObjectRequest request = invocation.getArgument(0);
            objects.put(request.key(), new byte[] {1});
            return PutObjectResponse.builder().build();
        });
        when(s3.deleteObject(any(DeleteObjectRequest.class))).thenAnswer(invocation -> {
            DeleteObjectRequest request = invocation.getArgument(0);
            objects.remove(request.key());
            return DeleteObjectResponse.builder().build();
        });
        S3ClientBuilder builder = mock(S3ClientBuilder.class, RETURNS_SELF);
        when(builder.build()).thenReturn(s3);
        clientFactory = mockStatic(S3Client.class);
        clientFactory.when(S3Client::builder).thenReturn(builder);
    }

    @AfterEach
    void tearDown() {
        if (clientFactory != null) {
            clientFactory.close();
        }
        jdbc.execute("SHUTDOWN");
    }

    @Test
    void committedUploadKeepsItsObjectAndPublicFileId() throws Exception {
        assertThat(service.uploadFile(file()).getData()).isEqualTo("123");

        String path = jdbc.queryForObject("SELECT path FROM file", String.class);
        assertThat(path).matches("rpa/\\d{4}-\\d{2}-\\d{2}/123-[0-9a-f-]{36}\\.png");
        assertThat(objects).containsKey(path);
        verify(s3, never()).deleteObject(any(DeleteObjectRequest.class));
    }

    @Test
    void rolledBackInsertRemovesOnlyThisUploadsObject() {
        objects.put("rpa/existing-shared-image.png", new byte[] {2});
        RuntimeException failure = new IllegalStateException("insert response lost");
        doAnswer(invocation -> {
                    realMapper.insert(invocation.getArgument(0));
                    throw failure;
                })
                .when(mapper)
                .insert(any(File.class));

        assertThatThrownBy(() -> service.uploadFile(file())).isSameAs(failure);

        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM file", Integer.class))
                .isZero();
        assertThat(objects).containsOnlyKeys("rpa/existing-shared-image.png");
    }

    @Test
    void zeroInsertedRowsRollsBackAndRemovesUpload() {
        doReturn(0).when(mapper).insert(any(File.class));

        assertThatThrownBy(() -> service.uploadFile(file()))
                .isInstanceOf(ServiceException.class)
                .hasMessage("文件信息保存失败");

        assertThat(objects).isEmpty();
    }

    @Test
    void duplicateFileIdNeverOverwritesOrDeletesTheCommittedObject() throws Exception {
        service.uploadFile(file());
        String committedPath = jdbc.queryForObject("SELECT path FROM file", String.class);
        doThrow(new IllegalStateException("second insert failed")).when(mapper).insert(any(File.class));

        assertThatThrownBy(() -> service.uploadFile(file())).isInstanceOf(RuntimeException.class);

        assertThat(objects).containsOnlyKeys(committedPath);
        assertThat(jdbc.queryForObject("SELECT path FROM file", String.class)).isEqualTo(committedPath);
    }

    @Test
    void uploadsWithTheSamePublicIdUseDifferentStorageObjects() throws Exception {
        service.uploadFile(file());
        service.uploadFile(file());

        assertThat(jdbc.queryForList("SELECT path FROM file", String.class))
                .hasSize(2)
                .doesNotHaveDuplicates()
                .containsExactlyInAnyOrderElementsOf(objects.keySet());
        verify(s3, never()).deleteObject(any(DeleteObjectRequest.class));
    }

    @Test
    void cleanupWaitsForTheOuterTransactionToRollBack() {
        new TransactionTemplate(transactionManager).executeWithoutResult(status -> {
            upload();
            assertThat(objects).hasSize(1);
            verify(s3, never()).deleteObject(any(DeleteObjectRequest.class));
            status.setRollbackOnly();
        });

        assertThat(objects).isEmpty();
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM file", Integer.class))
                .isZero();
    }

    @Test
    void unknownCommitOutcomeKeepsTheObjectEvenIfCommitActuallySucceeded() {
        dataSource.loseCommitResponse = true;
        transactionManager.setExceptionTranslator((task, sql, exception) -> null);

        assertThatThrownBy(() -> service.uploadFile(file())).isInstanceOf(TransactionSystemException.class);

        String committedPath = jdbc.queryForObject("SELECT path FROM file", String.class);
        assertThat(objects).containsOnlyKeys(committedPath);
        verify(s3, never()).deleteObject(any(DeleteObjectRequest.class));
    }

    @Test
    void rollbackAfterTranslatedCommitFailureCannotDeleteTheCommittedObject() {
        dataSource.loseCommitResponse = true;

        assertThatThrownBy(() -> service.uploadFile(file())).isInstanceOf(DataAccessException.class);

        String committedPath = jdbc.queryForObject("SELECT path FROM file", String.class);
        assertThat(objects).containsOnlyKeys(committedPath);
        verify(s3, never()).deleteObject(any(DeleteObjectRequest.class));
    }

    @Test
    void failedRollbackKeepsTheObject() {
        dataSource.failRollback = true;
        doThrow(new IllegalStateException("insert failed")).when(mapper).insert(any(File.class));

        assertThatThrownBy(() -> service.uploadFile(file())).isInstanceOf(DataAccessException.class);

        assertThat(objects).hasSize(1);
        verify(s3, never()).deleteObject(any(DeleteObjectRequest.class));
    }

    @Test
    void cleanupFailureDoesNotReplaceTheInsertFailure() {
        RuntimeException failure = new IllegalStateException("insert failed");
        doThrow(failure).when(mapper).insert(any(File.class));
        when(s3.deleteObject(any(DeleteObjectRequest.class)))
                .thenThrow(S3Exception.builder().message("storage unavailable").build());

        assertThatThrownBy(() -> service.uploadFile(file())).isSameAs(failure);

        assertThat(objects).hasSize(1);
    }

    @Test
    void alreadyAbsentObjectDoesNotReplaceTheInsertFailure() {
        RuntimeException failure = new IllegalStateException("insert failed");
        doThrow(failure).when(mapper).insert(any(File.class));
        when(s3.deleteObject(any(DeleteObjectRequest.class))).thenAnswer(invocation -> {
            objects.remove(((DeleteObjectRequest) invocation.getArgument(0)).key());
            throw NoSuchKeyException.builder().message("already absent").build();
        });

        assertThatThrownBy(() -> service.uploadFile(file())).isSameAs(failure);

        assertThat(objects).isEmpty();
    }

    @Test
    void unsuccessfulUploadDoesNotPersistOrDeleteAnything() {
        when(s3.putObject(any(PutObjectRequest.class), any(RequestBody.class)))
                .thenThrow(S3Exception.builder().message("storage unavailable").build());

        assertThatThrownBy(() -> service.uploadFile(file())).isInstanceOf(ServiceException.class);

        verifyNoInteractions(mapper);
        verify(s3, never()).deleteObject(any(DeleteObjectRequest.class));
    }

    @Test
    void missingTransactionIsRejectedBeforeUploading() {
        assertThatThrownBy(() -> target.uploadFile(file()))
                .isInstanceOf(ServiceException.class)
                .hasMessage("文件上传需要事务");

        verifyNoInteractions(s3, mapper);
    }

    private void upload() {
        try {
            service.uploadFile(file());
        } catch (IOException e) {
            throw new IllegalStateException(e);
        }
    }

    private MockMultipartFile file() {
        return new MockMultipartFile("file", "screenshot.png", "image/png", new byte[] {1});
    }

    private static class FaultInjectingDataSource extends DelegatingDataSource {
        private boolean loseCommitResponse;
        private boolean failRollback;

        FaultInjectingDataSource(JdbcDataSource dataSource) {
            super(dataSource);
        }

        @Override
        public Connection getConnection() throws SQLException {
            Connection connection = super.getConnection();
            return (Connection) Proxy.newProxyInstance(
                    Connection.class.getClassLoader(), new Class<?>[] {Connection.class}, (proxy, method, args) -> {
                        if (failRollback && "rollback".equals(method.getName())) {
                            throw new SQLTransientConnectionException("rollback failed", "08006");
                        }
                        try {
                            Object result = method.invoke(connection, args);
                            if (loseCommitResponse && "commit".equals(method.getName())) {
                                throw new SQLTransientConnectionException("commit response lost", "08006");
                            }
                            return result;
                        } catch (InvocationTargetException e) {
                            throw e.getCause();
                        }
                    });
        }
    }
}
